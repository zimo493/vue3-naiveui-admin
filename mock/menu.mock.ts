/*
 * 菜单 mock（内存态）
 * 数据取自 sql/youlai_admin.sql 的 sys_menu（菜单编号与图标用该脚本里的值）
 *  - GET  menus/routes   动态路由（RouteVO 树，供侧边菜单与 router.addRoute 使用）
 *  - GET  menus         菜单表格树（含按钮）
 *  - GET  menus/options 上级菜单下拉（可用 types=C,M 过滤按钮）
 *  - POST/PUT/DELETE    直接作用于内存数据，动态路由实时重算
 */

/** 菜单行（对应 sys_menu 字段） */
interface MenuRow {
  id: string;
  parentId: string;
  name: string;
  /** C=目录 M=菜单 B=按钮 */
  type: string;
  routeName: string | null;
  routePath: string;
  component: string | null;
  perm: string | null;
  alwaysShow: number | null;
  keepAlive: number | null;
  visible: number;
  sort: number;
  icon: string;
  redirect: string | null;
  params: Record<string, string> | null;
}

/** 路由节点（naiveui 的 AppRoute.RouteVO） */
interface RouteVO {
  path: string;
  name?: string;
  component?: string;
  redirect?: string;
  meta?: {
    title?: string;
    icon?: string;
    hidden?: boolean;
    alwaysShow?: boolean;
    keepAlive?: boolean;
    params?: Record<string, string>;
  };
  children?: RouteVO[];
}

