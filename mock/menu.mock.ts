let nextMenuId = 1000;

/** 目录没有 routeName 时的兜底路由名（如 /system -> System） */
function toPascalCase(routePath: string): string {
  return routePath
    .split(/[/\-_]/)
    .filter(Boolean)
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join("");
}

/** 按父 id 取子菜单（已按 sort 排序） */
const childrenOf = (parentId: string): MenuRow[] =>
  menuList.filter((m) => m.parentId === parentId).sort((a, b) => a.sort - b.sort);

/** 构建路由树（排除按钮；visible=0 标记 hidden） */
function buildRoutes(parentId = "0"): RouteVO[] {
  return childrenOf(parentId)
    .filter((m) => m.type !== "B")
    .map((m) => {
      const children = buildRoutes(m.id);
      const node: RouteVO = {
        path: m.routePath,
        name: m.routeName || (/^https?:/.test(m.routePath) ? undefined : toPascalCase(m.routePath)),
        component: m.component ?? undefined,
        meta: {
          title: m.name,
          ...(m.icon ? { icon: m.icon } : {}),
          ...(m.keepAlive === 1 ? { keepAlive: true } : {}),
          ...(m.visible === 0 ? { hidden: true } : {}),
          ...(m.alwaysShow === 1 ? { alwaysShow: true } : {}),
          ...(m.params ? { params: m.params } : {}),
        },
      };

      if (m.redirect) node.redirect = m.redirect;
      if (children.length) node.children = children;

      return node;
    });
}

/** 构建菜单表格树（含按钮） */
function buildTableTree(parentId = "0"): Record<string, unknown>[] {
  return childrenOf(parentId).map((m) => {
    const children = buildTableTree(m.id);

    return {
      id: m.id,
      parentId: m.parentId,
      name: m.name,
      type: m.type,
      routeName: m.routeName,
      routePath: m.routePath,
      component: m.component,
      perm: m.perm,
      alwaysShow: m.alwaysShow ?? 0,
      keepAlive: m.keepAlive ?? 0,
      visible: m.visible,
      sort: m.sort,
      icon: m.icon,
      redirect: m.redirect,
      params: m.params ? Object.entries(m.params).map(([key, value]) => ({ key, value })) : [],
      ...(children.length ? { children } : {}),
    };
  });
}

/**
 * 菜单下拉树（n-tree / n-tree-select 需要 children 嵌套，扁平数组会被拍平）
 *  - 不传 types：返回全量树（含按钮），用于「角色 → 分配权限」的权限树
 *  - 传 types（如 "C,M"）：过滤掉按钮等类型，用于「菜单 → 上级菜单」选择器
 */
function buildOptions(types: string[], nodes = buildTableTree()): Record<string, unknown>[] {
  return nodes
    .filter((node) => !types.length || types.includes(String(node.type)))
    .map((node) => {
      const children = buildOptions(types, (node.children as Record<string, unknown>[]) ?? []);

      return {
        value: String(node.id),
        label: String(node.name),
        type: node.type,
        ...(children.length ? { children } : {}),
      };
    });
}

/** 按关键字过滤菜单表格树（命中节点保留祖先链） */
function filterTableTree(
  nodes: Record<string, unknown>[],
  lower: string
): Record<string, unknown>[] {
  return nodes.reduce<Record<string, unknown>[]>((acc, node) => {
    const children = filterTableTree((node.children as Record<string, unknown>[]) ?? [], lower);
    const hit = String(node.name ?? "")
      .toLowerCase()
      .includes(lower);

    if (hit || children.length) acc.push({ ...node, ...(children.length ? { children } : {}) });

    return acc;
  }, []);
}

